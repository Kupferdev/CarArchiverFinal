import assert from 'node:assert/strict';
import fs from 'node:fs';
const main = fs.readFileSync('electron/main.ts','utf8');
const ipc = fs.readFileSync('electron/ipcHandlers.ts','utf8');
const security = fs.readFileSync('electron/security.ts','utf8');
const policy = fs.readFileSync('electron/networkPolicy.ts','utf8');
const media = fs.readFileSync('src/main/data/serviceMedia.ts','utf8');
const trash = fs.readFileSync('src/main/data/trash.ts','utf8');
const html = fs.readFileSync('index.html','utf8');
assert.match(main, /setWindowOpenHandler/);
assert.match(main, /will-navigate/);
assert.match(main, /sandbox:true/);
// Catch the startup crash regression: a const window binding must exist before guards use it.
const initWindow = main.indexOf('const currentWindow = win;');
const guardWindow = main.indexOf('currentWindow.webContents.setWindowOpenHandler');
assert(initWindow >= 0 && guardWindow > initWindow, 'Window guards must run after currentWindow initialization');
assert(!main.includes("on('will-frame-navigate'"), 'Electron 30 does not expose will-frame-navigate');
assert.match(ipc, /event.senderFrame === event.sender.mainFrame/);
assert.match(ipc, /function secureHandle/);
assert(!/\bipcMain\.handle\('/.test(ipc), 'Direct IPC handle registration bypasses the sender check');
assert.match(ipc, /javascript: false/);
assert.match(security, /fileURLToPath/);
assert.match(html, /Content-Security-Policy/);
assert.match(main, /session\.defaultSession\.webRequest\.onBeforeRequest/);
assert.match(main, /isPermittedRendererRequest/);
assert.match(policy, /localhost/);
assert.match(media, /resolveManagedMediaFile/);
assert.match(trash, /resolveManagedMediaFile/);
assert.match(security, /target\.pathname === allowed\.pathname/);
console.log('Electron window, IPC sender and CSP security invariants passed.');

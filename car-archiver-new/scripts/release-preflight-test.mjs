import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const run = (args) => spawnSync(process.execPath, ['scripts/release-preflight.mjs', ...args], { cwd: project, encoding: 'utf8' });
const report = run([]);
assert.equal(report.status, 0, report.stderr);
assert.match(report.stdout, /PASS lockfile:/);
assert.match(report.stdout, /PASS ipc:/);
assert.doesNotMatch(report.stdout, /FAIL electron-age:/);
assert.match(report.stdout, /WARN electron-support:/);
assert.match(report.stdout, /WARN appx-version:/);
assert.match(report.stdout, /required gates passed/);
assert.match(report.stdout, /FAIL privacy:/);
assert.match(report.stdout, /PASS store-identity:/);
assert.match(report.stdout, /FAIL msix-validated:/);
assert.match(report.stdout, /PASS legacy-rebuilder:/);
assert.match(report.stdout, /No customer database or media directories were read/);
const strict = run(['--strict']);
assert.equal(strict.status, 1);
assert.match(strict.stdout, /still open/);
assert.match(strict.stdout, /WARN electron-support:/);
console.log('Release gate tests passed (informational succeeds; strict fails closed).');
